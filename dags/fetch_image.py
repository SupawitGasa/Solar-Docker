import math
import os
import time
import tomllib
from pathlib import Path

from airflow.providers.mysql.hooks.mysql import MySqlHook

STEP_NAME = "fetch_image"
MAX_RETRIES = 5

# Tile parameters
ZOOM = 20
TILE_SIZE = 256
TILE_URL_TEMPLATE = "https://mt{server}.google.com/vt/lyrs=s&x={x}&y={y}&z={z}"
REQUEST_DELAY_SEC = 0.3
REQUEST_TIMEOUT_SEC = 10
MAX_TILES = 400

# Folder that task 1 writes config_<tid>.toml into
CONFIG_DIR = '/opt/airflow/toml_config_files/'

# Resolution (meters per pixel on the ground) that the model was trained on (10 cm/pixel)
TARGET_RES_M = 0.10
# Size of one pixel in EPSG:3857 meters at this zoom level (at the equator)
ZOOM_PIXEL_M = 40075016. / (TILE_SIZE * 2 ** ZOOM)

# -----------------------------------------------------------------------------
# Coordinate helpers (Slippy Map / Web Mercator)
# -----------------------------------------------------------------------------

def lnglat_to_tile(lng, lat, zoom):
    # Convert latitude & longitude (degrees) into fractional tile location x, y
    lat_rad = math.radians(lat)
    n = 2.0 ** zoom
    x = (lng + 180.0) / 360.0 * n
    y = (1.0 - math.log(math.tan(lat_rad) + 1.0 / math.cos(lat_rad)) / math.pi) / 2.0 * n
    return x, y

def tile_to_lnglat(x, y, zoom):
    # Convert tile location x, y into latitude & longitude (degrees)
    n = 2.0 ** zoom
    lng = x / n * 360.0 - 180.0
    lat_rad = math.atan(math.sinh(math.pi * (1 - 2 * y / n)))
    lat = math.degrees(lat_rad)
    return lng, lat

def lnglat_to_webmercator(lng, lat):
    # Convert latitude & longitude (degrees) into meters in EPSG:3857 (Web Mercator)
    original_shift = 20037508.34
    x = lng * original_shift / 180.0
    y = math.log(math.tan((90 + lat) * math.pi / 360.0)) / (math.pi / 180.0)
    y = y * original_shift / 180.0
    return x, y

def fetch_tile(x, y, zoom, server=0):
    # Download 1 tile and return it as a PIL Image
    import io

    import requests
    from PIL import Image

    url = TILE_URL_TEMPLATE.format(server=server, x=x, y=y, z=zoom)
    headers = {"User-Agent": "Mozilla/5.0"}
    response = requests.get(url, headers=headers, timeout=REQUEST_TIMEOUT_SEC)
    response.raise_for_status()
    return Image.open(io.BytesIO(response.content)).convert("RGB")

# -----------------------------------------------------------------------------
# The actual image work for ONE task (shared by pending and retry paths)
# -----------------------------------------------------------------------------

def create_geotiff(tid, title, min_lat, min_lng, max_lat, max_lng):
    # Heavy imports live here, so DAG parsing stays fast
    import numpy as np
    import rasterio
    from PIL import Image
    from rasterio.transform import from_bounds

    # Verify the coordinates
    if min_lat >= max_lat or min_lng >= max_lng:
        raise ValueError(f"Invalid BBOX: lat {min_lat}-{max_lat}, lng {min_lng}-{max_lng}")

    # Retrieves the input folder path from the config file generated by task 1
    config_file_path = os.path.join(CONFIG_DIR, f"config_{tid}.toml")

    with open(config_file_path, "rb") as file:
        cfg = tomllib.load(file)["inference"]

    input_folder_path = Path(cfg["inference_path"]) / cfg["input_folder"]

    # A: Find which tile indices cover the desired region
    x_min_f, y_min_f = lnglat_to_tile(min_lng, max_lat, ZOOM) # top-left corner
    x_max_f, y_max_f = lnglat_to_tile(max_lng, min_lat, ZOOM) # bottom-right corner

    x_start, x_end = int(math.floor(x_min_f)), int(math.floor(x_max_f))
    y_start, y_end = int(math.floor(y_min_f)), int(math.floor(y_max_f))

    n_cols = x_end - x_start + 1
    n_rows = y_end - y_start + 1
    n_tiles = n_rows * n_cols

    # Ensure that the image is not too large
    if n_tiles > MAX_TILES:
        raise ValueError(
            f"Requested area is too large ({n_tiles} tiles, limit {MAX_TILES})."
            f"Please select a smaller region."
        )

    # B: Create an empty canvas and paste tiles onto it
    mosaic = Image.new("RGB", (n_cols * TILE_SIZE, n_rows * TILE_SIZE))

    server_cycle = 0
    for row, y in enumerate(range(y_start, y_end + 1)):
        for col, x in enumerate(range(x_start, x_end + 1)):
            tile_img = fetch_tile(x, y, ZOOM, server=server_cycle % 4) # rotate among mt0 - mt3
            mosaic.paste(tile_img, (col * TILE_SIZE, row * TILE_SIZE))
            server_cycle += 1
            time.sleep(REQUEST_DELAY_SEC) # lower the request frequency

    # C: Geographical boundaries of the merged image
    lng_left, lat_top = tile_to_lnglat(x_start, y_start, ZOOM)
    lng_right, lat_bottom = tile_to_lnglat(x_end + 1, y_end + 1, ZOOM)

    left_m, top_m = lnglat_to_webmercator(lng_left, lat_top)
    right_m, bottom_m = lnglat_to_webmercator(lng_right, lat_bottom)

    # Resample the mosaic to match the model's training resolution (~10 cm/pixel)
    # EPSG:3857 stretches distance by 1/cos(lat), so the real ground resolution
    # of a Google tile is ZOOM_PIXEL_M * cos(lat), not ZOOM_PIXEL_M itself
    mid_lat = (lat_top + lat_bottom) / 2
    ground_res_m = ZOOM_PIXEL_M * math.cos(math.radians(mid_lat))
    scale = ground_res_m / TARGET_RES_M # >1 means upscale

    new_size = (round(mosaic.width * scale), round(mosaic.height * scale))

    # Resize only once, with LANCZOS (sharp edges for panel borders)
    mosaic = mosaic.resize(new_size, Image.Resampling.LANCZOS)

    # D: Write the mosaic to a GeoTIFF
    input_folder_path.mkdir(parents=True, exist_ok=True)

    # Rasterio expects (bands, height, width), not (height, width, bands)
    mosaic_array = np.array(mosaic).transpose(2, 0, 1)

    transform = from_bounds(
        left_m, bottom_m, right_m, top_m,
        mosaic.width, mosaic.height
    )

    image_path = input_folder_path / f"{title}.tif"

    with rasterio.open(
        image_path,
        "w",
        driver="GTiff",
        height=mosaic.height,
        width=mosaic.width,
        count=3, # RGB
        dtype=mosaic_array.dtype,
        crs="EPSG:3857", # Web Mercator
        transform=transform   
    ) as dst:
        dst.write(mosaic_array)

    return image_path

# -----------------------------------------------------------------------------
# Status bookkeeping for ONE task
# -----------------------------------------------------------------------------

def process_task(connection, cursor, task):
    tid = task['tid']
    title = task['title']

    try:
        # Mark Task_Step and Task as running
        cursor.execute(
            """
            UPDATE task_step
            SET status = 'running', started_at = CURRENT_TIMESTAMP
            WHERE tid = %s AND step_name = %s;
            """,
            (tid, STEP_NAME),
        )
        cursor.execute(
            """
            UPDATE task
            SET status = 'fetch_image:running'
            WHERE tid = %s;
            """,
            (tid,),
        )

        image_path = create_geotiff(
            tid,
            title,
            float(task['bbox_min_lat']),
            float(task['bbox_min_lng']),
            float(task['bbox_max_lat']),
            float(task['bbox_max_lng']),
        )
        print(f"Saved GeoTIFF image at: {image_path}")

        # Mark Task_Step and Task as completed and hand over to the next step
        cursor.execute(
            """
            UPDATE task_step
            SET status = 'completed', completed_at = CURRENT_TIMESTAMP, error_msg = NULL
            WHERE tid = %s AND step_name = %s;
            """,
            (tid, STEP_NAME),
        )
        cursor.execute(
            """
            UPDATE task
            SET status = 'run_inference:pending'
            WHERE tid = %s;
            """,
            (tid,),
        )

        connection.commit()
        print(f"Task ID {tid} status updated to 'run_inference:pending'.\n")

        return True

    except Exception as task_err:
        # Throw away the half-done change, then record the failure
        connection.rollback()
        error_message = str(task_err)
        print(f"Failed to fetch image for Task ID {tid}: {error_message}")

        cursor.execute(
            """
            UPDATE task_step
            SET status = 'failed', error_msg = %s, completed_at = CURRENT_TIMESTAMP
            WHERE tid = %s AND step_name = %s;
            """,
            (error_message, tid, STEP_NAME),
        )
        cursor.execute(
            """
            UPDATE task
            SET status = 'fetch_image:failed'
            WHERE tid = %s;
            """,
            (tid,),
        )

        connection.commit()
        print(f"Task ID {tid} status updated to 'fetch_image:failed'.\n")

        return False

